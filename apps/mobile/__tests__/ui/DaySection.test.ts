import { dayLabel } from '../../src/ui/DaySection';

const L = { today: 'วันนี้', yesterday: 'เมื่อวาน' };

describe('หัวข้อวันของรายการย้อนหลัง', () => {
  it('วันนี้กับเมื่อวานอ่านเป็นคำ ไม่ใช่ตัวเลข', () => {
    expect(dayLabel('2026-09-02', '2026-09-02', '2026-09-01', L)).toBe('วันนี้');
    expect(dayLabel('2026-09-01', '2026-09-02', '2026-09-01', L)).toBe('เมื่อวาน');
  });

  it('วันอื่นเป็นวันที่ย่อภาษาไทย', () => {
    expect(dayLabel('2026-08-28', '2026-09-02', '2026-09-01', L)).toBe('28 ส.ค.');
  });

  it('สลับเป็นอังกฤษตามภาษาที่เลือก', () => {
    expect(dayLabel('2026-08-28', '2026-09-02', '2026-09-01', L, 'en')).toBe('Aug 28');
  });
});
