/**
 * เลือกชื่อที่จะโชว์ตามภาษาที่ผู้ใช้ตั้งไว้
 *
 * ทำที่ชั้นข้อมูล ไม่ใช่ที่จอ เพราะมีจุดที่เรนเดอร์ชื่ออยู่ห้าสิบกว่าจุด
 * ถ้าให้แต่ละจอเลือกเอง จะมีจุดที่ลืมเสมอ และจุดที่ลืมคือจุดที่ผู้ใช้เจอ
 *
 * ไม่มีชื่ออังกฤษก็ตกกลับไปใช้ชื่อไทย ร้านที่เจ้าของเพิ่งสมัครยังไม่ได้กรอกชื่ออังกฤษ
 * ปล่อยให้ชื่อหายไปทั้งชื่อแย่กว่าโชว์ภาษาที่อ่านไม่ออก
 */
export function localName(
  name: string,
  nameEn: string | null | undefined,
  language: string,
): string {
  if (language.startsWith('th')) return name;
  const en = nameEn?.trim();
  return en ? en : name;
}
